def run_seed():
    """درج داده اولیه در صورت خالی بودن جداول"""
    if Service.query.count() == 0:
        for i, data in enumerate(SERVICES):
            slug = data["title"].replace(" ", "-")
            db.session.add(Service(
                title=data["title"], slug=slug, icon=data["icon"],
                short_desc=data["short_desc"], description=data["description"],
                price=data["price"], duration_minutes=data["duration_minutes"],
                is_active=True, sort_order=i,
            ))

    if Psychologist.query.count() == 0:
        for i, data in enumerate(PSYCHOLOGISTS):
            db.session.add(Psychologist(
                name=data["name"], title=data["title"], specialty=data["specialty"],
                degree=data["degree"], bio=data["bio"], experience_years=data["experience_years"],
                consults_count=data["consults_count"], rating=data["rating"],
                is_active=True, sort_order=i,
            ))
        db.session.flush()

        teachers = Psychologist.query.all()
        for data in COURSES:
            teacher = teachers[data["teacher_idx"]] if data["teacher_idx"] < len(teachers) else None
            db.session.add(Course(
                title=data["title"], teacher_id=teacher.id if teacher else None,
                icon=data["icon"], summary=data["summary"], description=data["description"],
                price=data["price"], sessions_count=data["sessions_count"],
                duration_minutes=data["duration_minutes"], capacity=data["capacity"],
                start_date=data["start_date"], format=data["format"], is_active=True,
            ))

    if Article.query.count() == 0:
        for data in ARTICLES:
            slug = data["title"].replace(" ", "-").replace("؟", "")
            db.session.add(Article(
                title=data["title"], slug=slug, category=data["category"],
                excerpt=data["excerpt"], content=data["content"],
                reading_time=data["reading_time"], icon=data["icon"],
                is_published=True, views=0,
            ))

    if ContactMessage.query.count() == 0:
        for data in SAMPLE_MESSAGES:
            db.session.add(ContactMessage(**data))

    db.session.commit()
